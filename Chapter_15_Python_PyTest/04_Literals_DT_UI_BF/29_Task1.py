# Task for the Today
# Take a 3 input from the user
# perform the sum, sub, mul and div

input1 = int(input("Enter the first number: "))
input2 = int(input("Enter the second number: "))
input3 = int(input("Enter the third number: "))

sum_result = input1 + input2 + input3
sub_result = input1 - input2 - input3
mul_result = input1 * input2 * input3
div_result = input1 / input2 / input3

print(f"Sum: {sum_result}")
print(f"Subtraction: {sub_result}")
print(f"Multiplication: {mul_result}")
print(f"Division: {div_result}")